'use strict';

/**
 * controllers/ojt.controller.js
 * ─────────────────────────────────────────────────────────────────────────────
 * HTTP controller layer for OJT management API.
 * Delegates business logic to ojtService and logs security audit events.
 */

const ojtService = require('../services/ojtService');
const auditService = require('../services/auditService');

async function listOjts(req, res, next) {
    try {
        const result = await ojtService.listOjts();
        return res.status(result.status).json(result.data);
    } catch (err) {
        next(err);
    }
}

async function getOjt(req, res, next) {
    try {
        const { userId } = req.params;
        const result = await ojtService.getOjtById(userId);
        if (result.error) {
            return res.status(result.status).json({ error: result.error });
        }
        return res.status(result.status).json(result.data);
    } catch (err) {
        next(err);
    }
}

async function createOjt(req, res, next) {
    try {
        const result = await ojtService.createOjt(req.body);
        if (result.error) {
            return res.status(result.status).json({ error: result.error });
        }

        const createdUser = result.data.user;
        await auditService.logSecurityEvent({
            req,
            action: 'OJT_ACCOUNT_CREATE',
            resourceType: 'USER',
            resourceId: createdUser.User_ID,
            details: {
                name: createdUser.Name,
                email: createdUser.Email,
                startDate: createdUser.OJT_Start_Date,
                endDate: createdUser.OJT_End_Date
            },
            result: 'SUCCESS'
        });

        return res.status(result.status).json(result.data);
    } catch (err) {
        next(err);
    }
}

async function updateOjt(req, res, next) {
    try {
        const { userId } = req.params;
        const result = await ojtService.updateOjt(userId, req.body);
        if (result.error) {
            return res.status(result.status).json({ error: result.error });
        }

        const updatedUser = result.data.user;
        await auditService.logSecurityEvent({
            req,
            action: 'OJT_ACCOUNT_UPDATE',
            resourceType: 'USER',
            resourceId: Number(userId),
            details: {
                name: updatedUser.Name,
                email: updatedUser.Email,
                startDate: updatedUser.OJT_Start_Date,
                endDate: updatedUser.OJT_End_Date
            },
            result: 'SUCCESS'
        });

        return res.status(result.status).json(result.data);
    } catch (err) {
        next(err);
    }
}

async function updateStatus(req, res, next) {
    try {
        const { userId } = req.params;
        const { status } = req.body;
        const result = await ojtService.updateStatus(userId, status);
        if (result.error) {
            return res.status(result.status).json({ error: result.error });
        }

        const action = status === 'ACTIVE' ? 'OJT_ACCOUNT_ACTIVATE' : 'OJT_ACCOUNT_DEACTIVATE';
        await auditService.logSecurityEvent({
            req,
            action,
            resourceType: 'USER',
            resourceId: Number(userId),
            details: { newStatus: status },
            result: 'SUCCESS'
        });

        return res.status(result.status).json(result.data);
    } catch (err) {
        next(err);
    }
}

async function resetPassword(req, res, next) {
    try {
        const { userId } = req.params;
        const result = await ojtService.resetPassword(userId);
        if (result.error) {
            return res.status(result.status).json({ error: result.error });
        }

        await auditService.logSecurityEvent({
            req,
            action: 'OJT_PASSWORD_RESET',
            resourceType: 'USER',
            resourceId: Number(userId),
            details: { message: 'Temporary password generated by MIS Staff' },
            result: 'SUCCESS'
        });

        return res.status(result.status).json(result.data);
    } catch (err) {
        next(err);
    }
}

module.exports = {
    listOjts,
    getOjt,
    createOjt,
    updateOjt,
    updateStatus,
    resetPassword
};
